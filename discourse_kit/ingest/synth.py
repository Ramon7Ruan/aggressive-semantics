def generate(*, seed: int = 42, perfamily: tuple[int, int] = (4, 11),
             platform: str = "synthetic", board: str = "社会话题",
             start: datetime | None = None,
             long_ratio: float = 0.18) -> list[dict]:
    """生成规范格式（schema v1）的记录列表。"""
    rng = random.Random(seed)
    start = start or datetime(2024, 3, 1, 9, 0, 0)
    rows: list[dict] = []
    t = start
    idx = 0
    for code, topics in TOPICS.items():
        for title, body in topics:
            idx += 1
            tid = f"{platform}-thr-{idx:03d}"
            op_time = t
            rows.append({
                "doc_id": f"{tid}-000",
                "thread_id": tid,
                "unit": UNIT_OPENING,
                "text": body,
                "topic_id": f"{code}-{idx:03d}",
                "topic_title": title,
                "floor_no": 0,
                "author_id": f"op{idx}",
                "posted_at": op_time.strftime("%Y-%m-%d %H:%M:%S"),
                "is_op": True,
                "platform": platform,
                "board": board,
                "source": "synthetic",
            })
            n = rng.randint(*perfamily)
            pool = REPLIES[code]
            longs = LONG_REPLIES.get(code, [])
            used: list[str] = []
            for k in range(1, n + 1):
                cand = [s for s in pool if s not in used] or pool
                text = rng.choice(cand)
                used.append(text)
                if longs and rng.random() < long_ratio:
                    text = rng.choice(longs)
                if rng.random() < 0.25 and len(used) > 1:
                    text = f"引用：{rng.choice(used[:-1])}\n{text}"
                rows.append({
                    "doc_id": f"{tid}-{k:03d}",
                    "thread_id": tid,
                    "unit": UNIT_REPLY,
                    "text": text,
                    "topic_id": f"{code}-{idx:03d}",
                    "topic_title": title,
                    "floor_no": k,
                    "author_id": f"user{rng.randint(1, 40)}",
                    "posted_at": (op_time + timedelta(minutes=rng.randint(5, 900))).strftime(
                        "%Y-%m-%d %H:%M:%S"),
                    "has_quote": text.startswith("引用："),
                    "platform": platform,
                    "board": board,
                    "source": "synthetic",
                })
            t += timedelta(days=rng.randint(1, 4))
    return rows


def write_jsonl(path: str, rows: list[dict]) -> str:
    import json

    with open(path, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    return path


def write_csv_messy(path: str, rows: list[dict]) -> str:
    """故意用「脏表头 + 中文列名 + 混排字段」写出，测试映射导入器。"""
    import csv

    header = ["序号", "帖子ID", "楼层", "内容", "用户名", "发布时间", "话题标题",
              "板块", "回复数", "浏览数"]
    with open(path, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        for i, r in enumerate(rows, start=1):
            w.writerow([
                f"row{i}", r["thread_id"], r.get("floor_no", ""), r["text"],
                r.get("author_id", ""), r.get("posted_at", ""),
                r.get("topic_title", ""), r.get("board", ""),
                r.get("reply_count", ""), r.get("view_count", ""),
            ])
    return path
